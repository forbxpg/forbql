def check_view(definition: str | None, ctx: CheckContext) -> list[Violation]:
    """Check a view's query the way a user query is checked.

    A view runs as its owner, so column grants do not apply inside it. The same
    statement, object, column, function, PII and complexity gates apply. The view
    is not rewritten, and its row limit is not enforced.

    Args:
        definition: str | None - The view's query, or its `CREATE VIEW` statement,
            whose query the check walks into; None when the role may not read it.
        ctx: CheckContext - Inputs of the check.

    Returns:
        list[Violation] - Problems found; a definition nobody can read is one.

    """
    if definition is None:
        return [
            Violation(
                rule=RuleId.PARSE_ERROR,
                message="the view's definition cannot be read",
                hint="let the role read view definitions (SHOW VIEW on MySQL)",
            ),
        ]
    tree = parse(definition, ctx)
    if isinstance(tree, list):
        return tree
    return _check_query(_view_query(tree), ctx)


def views_read(
    sql: str,
    *,
    engine: Engine,
    default_schema: str,
    views: Mapping[str, str | None],
) -> tuple[str, ...]:
    """Return the views a checked query reads.

    Args:
        sql: str - SQL regenerated by the firewall.
        engine: Engine - The connection's engine.
        default_schema: str - Schema of an unqualified name.
        views: Mapping[str, str | None] - Definitions by `schema.view`.

    Returns:
        tuple[str, ...] - Views the query reads, in name order. Every view when the
            SQL cannot be parsed, so a later change is not skipped.

    """
    if not views:
        return ()
    dialect = DIALECTS[engine]
    known = {dialect.fold(name): name for name in views}
    try:
        tree = sqlglot.parse_one(sql, read=dialect.engine.value)
    except SqlglotError:
        return tuple(sorted(views))
    cte_references = _cte_references(tree)
    default = dialect.fold(default_schema)
    found: set[str] = set()
    for table in tree.find_all(exp.Table):
        if id(table) in cte_references or not isinstance(table.this, exp.Identifier):  # pyright: ignore[reportAny]
            continue
        schema = table.db or default
        name = known.get(dialect.fold(f"{schema}.{table.name}"))
        if name is not None:
            found.add(name)
    return tuple(sorted(found))


def views_used(
    sql: str,
    *,
    engine: Engine,
    default_schema: str,
    views: Mapping[str, str | None],
) -> tuple[str, ...]:
    """Return the views a query reads, and the views named in their definitions.

    The definitions are the ones checked when the session opened. A view those
    definitions name is included, so replacing it is visible even when the outer
    text is unchanged.

    Args:
        sql: str - SQL regenerated by the firewall.
        engine: Engine - The connection's engine.
        default_schema: str - Schema of an unqualified name.
        views: Mapping[str, str | None] - Definitions by `schema.view`.

    Returns:
        tuple[str, ...] - Those views, in name order.

    """
    pending = list(
        views_read(
            sql,
            engine=engine,
            default_schema=default_schema,
            views=views,
        ),
    )
    seen: set[str] = set()
    while pending:
        name = pending.pop()
        if name in seen:
            continue
        seen.add(name)
        definition = views.get(name)
        if definition is None:
            continue
        pending.extend(
            views_read(
                definition,
                engine=engine,
                default_schema=default_schema,
                views=views,
            ),
        )
    return tuple(sorted(seen))


def _view_query(tree: exp.Expr) -> exp.Expr:
    """Return the query inside a `CREATE VIEW`, or the statement itself.

    Args:
        tree: exp.Expr - A parsed view definition.

    Returns:
        exp.Expr - The query the view runs.

    """
    if isinstance(tree, exp.Create) and tree.kind == "VIEW":
        query = _create_query(tree)
        if query is not None:
            return query
    return tree


def _create_query(tree: exp.Create) -> exp.Expr | None:
    """Return the query of a `CREATE` statement when it has one.

    Args:
        tree: exp.Create - The statement.

    Returns:
        exp.Expr | None - The query, or None when the statement has none.

    """
    query = cast("object", tree.expression)
    if isinstance(query, exp.Expr):
        return query
    return None


def _check_query(tree: exp.Expr, ctx: CheckContext) -> list[Violation]:
    """Run the query gates, stopping at the first one that finds problems.

    Args:
        tree: exp.Expr - The view's query.
        ctx: CheckContext - Inputs of the check.

    Returns:
        list[Violation] - Problems found.

    """
    query = check_statement(tree)
    if isinstance(query, list):
        return query
    if violations := check_objects(query, ctx):
        return violations
    query, violations = check_columns(query, ctx)
    if violations or (violations := check_functions(query, ctx)):
        return violations
    _, violations = check_pii(query, ctx)
    if violations or (violations := check_complexity(query, ctx)):
        return violations
    return []


def _cte_references(tree: exp.Expr) -> set[int]:
    """Find table nodes that name a CTE, not a stored relation.

    Args:
        tree: exp.Expr - The parsed query.

    Returns:
        set[int] - Identities of those nodes.

    """
    found: set[int] = set()
    for scope in traverse_scope(tree):
        found.update(
            id(table)
            for table in scope.tables
            if not table.db and table.name in scope.cte_sources
        )
    return found
